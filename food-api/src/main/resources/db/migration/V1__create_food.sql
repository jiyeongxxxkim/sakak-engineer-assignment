CREATE TABLE food (
    id                    BIGINT        NOT NULL AUTO_INCREMENT,
    food_cd               VARCHAR(20)   NOT NULL,
    group_name            VARCHAR(50),
    food_name             VARCHAR(100)  NOT NULL,
    research_year         SMALLINT,
    maker_name            VARCHAR(50),
    ref_name              VARCHAR(100),
    serving_size          DECIMAL(10,2),
    serving_unit          VARCHAR(10),
    calorie               DECIMAL(10,2),
    carbohydrate          DECIMAL(10,2),
    protein               DECIMAL(10,2),
    fat                   DECIMAL(10,2),
    sugars                DECIMAL(10,2),
    sodium                DECIMAL(10,2),
    cholesterol           DECIMAL(10,2),
    saturated_fatty_acids DECIMAL(10,2),
    trans_fat             DECIMAL(10,2),
    food_name_search      VARCHAR(100)  NOT NULL,
    maker_name_search     VARCHAR(50),
    PRIMARY KEY (id),
    CONSTRAINT uk_food_cd UNIQUE (food_cd),
    INDEX idx_food_research_year (research_year)
);
